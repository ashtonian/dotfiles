//go:build !windows

package atomicfile

import (
	"fmt"
	"os"
)

// syncDir flushes a directory's entries, which the rename changed.
func syncDir(dir string) error {
	d, err := os.Open(dir)
	if err != nil {
		return fmt.Errorf("sync %s: %w", dir, err)
	}
	defer d.Close()
	if err := d.Sync(); err != nil {
		return fmt.Errorf("sync %s: %w", dir, err)
	}
	return nil
}
