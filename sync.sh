#!/usr/bin/env bash
# Sync dotfiles, this machine's overlays and auxiliary repositories; install
# missing shared packages.
set -euo pipefail
umask 077

# shellcheck source=lib_sh/rotate-log.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib_sh/rotate-log.sh"
# shellcheck source=lib_sh/brew-root.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib_sh/brew-root.sh"
# shellcheck source=lib_sh/sync-lock.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib_sh/sync-lock.sh"
# shellcheck source=lib_sh/private-names.sh
source "$(dirname "${BASH_SOURCE[0]}")/lib_sh/private-names.sh"

DOTFILES_DIR=$(cd "${DOTFILES_DIR:-$HOME/.dotfiles}" && pwd -P)
SYNC_DIR="${SYNC_DIR:-$HOME/.sync}"
LOG_DIR="$DOTFILES_DIR/logs"
LOG_FILE="$LOG_DIR/sync.log"
# A repository with a tracked change newer than this is being edited; sync
# leaves it for a later run instead of committing half-finished work.
SYNC_QUIET_MINUTES="${SYNC_QUIET_MINUTES:-30}"
# Reachability check before any network step: a HEAD request, so a slow page
# body (github.com's is about 500 KB) never reads as no network.
SYNC_CONNECTIVITY_URL="${SYNC_CONNECTIVITY_URL:-https://github.com}"
SYNC_CONNECTIVITY_TIMEOUT="${SYNC_CONNECTIVITY_TIMEOUT:-15}"
# The feature engine (cmd/dotfiles): this machine's manifest, the binary sync
# builds from the checkout, and where apply writes the generated Brewfile.
MACHINE_FILE="$HOME/.config/dotfiles/machine.toml"
DOTFILES_BIN="${DOTFILES_BIN:-$HOME/.local/bin/dotfiles}"
GENERATED_DIR="$HOME/.config/dotfiles/generated"
# Claude Code comes from Anthropic's native installer, never Homebrew: the cask
# trails the releases, and the native install in ~/.local/bin updates itself.
CLAUDE_CODE_INSTALLER_URL="${CLAUDE_CODE_INSTALLER_URL:-https://claude.ai/install.sh}"
# The installer's own downloads have no timeout; this bounds the whole install.
CLAUDE_CODE_INSTALL_TIMEOUT="${CLAUDE_CODE_INSTALL_TIMEOUT:-900}"

log() { printf '[%s] %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$*" | tee -a "$LOG_FILE"; }
run_logged() { "$@" 2>&1 | tee -a "$LOG_FILE"; }
stable_host() { scutil --get LocalHostName 2>/dev/null || hostname -s; }

# acquire_lock: take the sync lock without waiting (lib_sh/sync-lock.sh). A
# scheduled sync that finds a run in progress has nothing to add to it.
acquire_lock() {
    local status=0
    sync_lock_take "$LOG_DIR" 0 || status=$?
    case $status in
        0) ;;
        75) log "INFO: Another sync or update is already running" ;;
        *) log "ERROR: Cannot acquire sync lock (exit $status)" ;;
    esac
    return "$status"
}

check_connectivity() {
    if ! curl -sfI -o /dev/null --connect-timeout 5 -m "$SYNC_CONNECTIVITY_TIMEOUT" "$SYNC_CONNECTIVITY_URL" 2>/dev/null; then
        log "WARN: No network connectivity ($SYNC_CONNECTIVITY_URL did not answer within ${SYNC_CONNECTIVITY_TIMEOUT}s), skipping sync"
        return 1
    fi
}

# missing_root_entries FILE: the entries of a Brewfile that this Mac lacks and
# that install only as root, one per line: `cask NAME`, or `mas ID NAME` (mas 7
# installs every App Store app as root).
missing_root_entries() {
    local file=$1 listed installed name missing=() wanted have id
    listed=$(HOMEBREW_NO_AUTO_UPDATE=1 brew bundle list --cask --file="$file") || return
    installed=$(brew list --cask -1 2>/dev/null) || installed=""
    while IFS= read -r name; do
        [[ -n "$name" ]] || continue
        grep -qxF "${name##*/}" <<<"$installed" || missing+=("$name")
    done <<<"$listed"
    if [[ ${#missing[@]} -gt 0 ]]; then
        brew_casks_needing_root "${missing[@]}" | sed 's/^/cask /' || return
    fi
    wanted=$(sed -nE 's/^[[:space:]]*mas[[:space:]]+"([^"]*)".*id:[[:space:]]*([0-9]+).*/\2 \1/p' "$file")
    [[ -n "$wanted" ]] || return 0
    have=$(mas list 2>/dev/null | awk '{ print $1 }') || have=""
    while read -r id name; do
        grep -qxF "$id" <<<"$have" || printf 'mas %s %s\n' "$id" "$name"
    done <<<"$wanted"
}

# sync_brewfile: install what the Brewfiles list and this Mac lacks, never
# upgrading. A run that cannot ask for a password (a LaunchAgent has no
# terminal) leaves the entries that install only as root for a terminal, names
# them in a warning, and installs the rest; HOMEBREW_NO_SUDO stops Homebrew
# from trying sudo for anything the list missed.
sync_brewfile() {
    if ! command -v brew >/dev/null; then
        log "WARN: Homebrew is not installed"
        return 1
    fi
    local file result=0 unattended=false
    brew_root_available || unattended=true
    # The enabled features' packages, generated by `dotfiles apply`, then this
    # machine's own.
    for file in "$GENERATED_DIR/Brewfile" "$DOTFILES_DIR/Brewfile.local"; do
        [[ -f "$file" ]] || continue
        if HOMEBREW_NO_AUTO_UPDATE=1 brew bundle check --no-upgrade --file="$file" >/dev/null 2>&1; then
            continue
        fi
        local env=(HOMEBREW_NO_AUTO_UPDATE=1)
        if [[ $unattended == true ]]; then
            local entries kind id rest casks="" mas_ids="" skipped=""
            if entries=$(missing_root_entries "$file"); then
                while read -r kind id rest; do
                    case $kind in
                        cask) casks+=" $id"; skipped+=", cask $id" ;;
                        mas) mas_ids+=" $id"; skipped+=", mas $rest ($id)" ;;
                    esac
                done <<<"$entries"
            else
                log "ERROR: Could not tell which of ${file##*/}'s missing casks need root; they fail below instead of waiting for a terminal"
                result=1
            fi
            env+=(HOMEBREW_NO_SUDO=1 "HOMEBREW_BUNDLE_CASK_SKIP=${casks# }" "HOMEBREW_BUNDLE_MAS_SKIP=${mas_ids# }")
            if [[ -n "$skipped" ]]; then
                log "WARN: Left ${skipped#, } for a terminal: they install as root and this run cannot ask for a password; run: brew bundle install --file=$file"
            fi
        fi
        log "INFO: Installing missing packages from ${file##*/}"
        if ! run_logged env "${env[@]}" brew bundle install --no-upgrade --file="$file"; then
            log "ERROR: Package installation failed for ${file##*/}"
            result=1
        fi
    done
    return "$result"
}

# The tools mise's configuration names: the default Node LTS, and the pinned Go
# a pull may just have moved. Installed here, after the merge, so no build
# downloads one on its first `go`. From $HOME, so only the shared and
# machine-wide configuration count, not a project the job happens to run in.
sync_mise_tools() {
    command -v mise >/dev/null || return 0
    local missing
    # A listing that fails falls through to the install, which reports why.
    if missing=$(mise -C "$HOME" ls --missing --global 2>&1) && [[ -z "$missing" ]]; then
        return 0
    fi
    log "INFO: Installing the tools mise's configuration names"
    if ! run_logged mise -C "$HOME" install --yes; then
        log "ERROR: mise could not install every tool; run: mise -C ~ install"
        return 1
    fi
}

# run_with_deadline SECONDS COMMAND...: run COMMAND in its own process group
# and, if it is still running after SECONDS, stop the group (so whatever it
# started stops too) and return 124.
run_with_deadline() (
    local deadline=$((SECONDS + $1)) pid
    shift
    # Job control gives the command its own group; the job notices it prints
    # go to the subshell's stderr, which is /dev/null, not the command's.
    exec 3>&2 2>/dev/null
    set -m
    "$@" </dev/null 2>&3 3>&- &
    pid=$!
    while kill -0 "$pid" 2>/dev/null; do
        if ((SECONDS >= deadline)); then
            kill -TERM -- "-$pid" 2>/dev/null
            wait "$pid" 2>/dev/null
            return 124
        fi
        sleep 1
    done
    wait "$pid"
)

# sync_claude_code: install Claude Code where agents.claude is enabled and
# ~/.local/bin/claude is missing. The installer checks the binary against the
# release manifest's SHA-256. Claude Code updates itself from then on, so sync
# never upgrades it.
sync_claude_code() {
    local claude="$HOME/.local/bin/claude" enabled installer status=0
    [[ -x "$claude" ]] && return 0
    if ! command -v jq >/dev/null; then
        log "ERROR: jq is not installed, so sync cannot tell whether this machine wants Claude Code"
        return 1
    fi
    if ! enabled=$("$DOTFILES_BIN" status --json | jq -r '.features[] | select(.id == "agents.claude") | .enabled'); then
        log "ERROR: $DOTFILES_BIN status did not list this machine's features; Claude Code not checked"
        return 1
    fi
    [[ "$enabled" == true ]] || return 0
    installer=$(mktemp "${TMPDIR:-/tmp}/claude-install.XXXXXX") || return 1
    if ! curl -fsSL --connect-timeout 10 --max-time 120 -o "$installer" "$CLAUDE_CODE_INSTALLER_URL"; then
        log "ERROR: downloading the Claude Code installer from $CLAUDE_CODE_INSTALLER_URL failed; the next sync retries"
        rm -f "$installer"
        return 1
    fi
    log "INFO: Installing Claude Code with $CLAUDE_CODE_INSTALLER_URL"
    # With ~/.local/bin on PATH the installer has no shell edit to suggest.
    run_logged run_with_deadline "$CLAUDE_CODE_INSTALL_TIMEOUT" env PATH="$HOME/.local/bin:$PATH" bash "$installer" || status=$?
    rm -f "$installer"
    if [[ $status -eq 124 ]]; then
        log "ERROR: the Claude Code installer did not finish within ${CLAUDE_CODE_INSTALL_TIMEOUT}s and was stopped; the next sync retries"
        return 1
    fi
    if [[ $status -ne 0 || ! -x "$claude" ]]; then
        log "ERROR: the Claude Code installer failed (exit $status); run: curl -fsSL $CLAUDE_CODE_INSTALLER_URL | bash"
        return 1
    fi
}

repo_idle() {
    local state location conflicts
    for state in MERGE_HEAD CHERRY_PICK_HEAD REVERT_HEAD rebase-merge rebase-apply sequencer BISECT_LOG; do
        location=$(git rev-parse --git-path "$state") || return
        if [[ -e "$location" ]]; then
            log "ERROR: Git operation in progress ($state); leaving repository unchanged"
            return 1
        fi
    done
    conflicts=$(git ls-files -u) || return
    if [[ -n "$conflicts" ]]; then
        log "ERROR: Unresolved Git conflicts; leaving repository unchanged"
        return 1
    fi
}

# Succeeds, and names the reason, when someone is working in the repository.
repo_busy() {
    local lock file
    lock=$(git rev-parse --git-path index.lock) || return 1
    if [[ -e "$lock" ]]; then
        log "INFO: ${PWD##*/} has a Git index lock; leaving it for the next sync"
        return 0
    fi
    while IFS= read -r -d '' file; do
        [[ -e "$file" ]] || continue
        if [[ -n "$(find "$file" -prune -mmin "-$SYNC_QUIET_MINUTES" 2>/dev/null)" ]]; then
            log "INFO: ${PWD##*/} changed in the last $SYNC_QUIET_MINUTES minutes ($file); leaving it for the next sync"
            return 0
        fi
    done < <(git diff --name-only -z HEAD --)
    return 1
}

signing_ready() {
    local name email key program enabled
    name=$(git config --get user.name) || name=''
    email=$(git config --get user.email) || email=''
    key=$(git config --get user.signingkey) || key=''
    program=$(git config --get gpg.program) || program='gpg'
    enabled=$(git config --get commit.gpgsign) || enabled='unset'
    if [[ -z "$name" || -z "$email" || -z "$key" ]] || ! command -v "$program" >/dev/null; then
        log "ERROR: Configure Git user.name, user.email, user.signingkey and a working gpg.program before syncing"
        return 1
    fi
    # Explicit -S is required even when commit.gpgsign is unset or false.
    [[ -n "$enabled" ]]
}

scan_dotfiles() {
    [[ "$PWD" == "$DOTFILES_DIR" ]] || return 0
    if ! command -v gitleaks >/dev/null; then
        log "ERROR: Install gitleaks before automatically publishing dotfiles"
        return 1
    fi
    if ! run_logged gitleaks git --no-banner --redact=100 --ignore-gitleaks-allow "$@" .; then
        log "ERROR: Secret scan failed; no commit or push will be attempted"
        return 1
    fi
    # The public repository names nothing an overlay keeps private.
    local found status=0
    [[ -f "$MACHINE_FILE" ]] || return 0
    found=$(private_names_found . "$DOTFILES_BIN") || status=$?
    case $status in
        0) log "ERROR: Tracked files name what an overlay keeps private; no commit or push will be attempted. Reword them or move them to the overlay:"
           printf '%s\n' "$found" | tee -a "$LOG_FILE"
           return 1 ;;
        1) ;;
        *) log "ERROR: Cannot list the overlays in $MACHINE_FILE for the private-name check; no commit or push will be attempted"; return 1 ;;
    esac
}

integrate_remote() {
    local branch="$1" auto_resolve="$2" before after remote
    remote="refs/remotes/origin/$branch"
    git rev-parse --verify "$remote" >/dev/null || return
    before=$(git rev-parse HEAD) || return
    local options=(--no-edit --gpg-sign)
    [[ "$auto_resolve" == true ]] && options+=(-X ours)
    if ! run_logged git merge "${options[@]}" "$remote"; then
        log "ERROR: Remote integration failed; aborting merge and skipping push"
        git merge --abort 2>/dev/null || true
        return 1
    fi
    after=$(git rev-parse HEAD) || return
    if [[ "$after" != "$before" && "$after" != "$(git rev-parse "$remote")" ]]; then
        run_logged git verify-commit "$after" || return
    fi
}

# upstream_ready REF: merging REF must leave this machine installable. When REF
# uses the feature engine, this machine needs its manifest, and REF's own
# engine has to build here and plan that manifest, before the merge. A merge
# that brought a layout the engine cannot install would leave every link the
# current layout made pointing at moved or changed files, with nothing to
# replace them: no shell config, no git identity for the next sync.
upstream_ready() {
    local ref="$1" profiles tree status=0
    git cat-file -e "$ref:features" 2>/dev/null || return 0
    [[ -n "$(git rev-list --max-count=1 "HEAD..$ref")" ]] || return 0
    if [[ ! -f "$MACHINE_FILE" ]]; then
        profiles=$(git ls-tree --name-only "$ref:profiles" 2>/dev/null | sed 's/\.toml$//' | tr '\n' ' ')
        log "ERROR: $ref installs machine features and this machine has no $MACHINE_FILE; skipping merge and push until it lists this machine's profiles, such as: profiles = [\"base\", \"dev\"] (available: ${profiles% })"
        return 1
    fi
    if ! command -v go >/dev/null; then
        log "ERROR: $ref installs machine features and Go is not installed to build its engine; skipping merge and push until Go is installed (brew install go)"
        return 1
    fi
    tree=$(mktemp -d "${TMPDIR:-/tmp}/dotfiles-upstream.XXXXXX") || return
    if git archive --format=tar "$ref" | tar -x -f - -C "$tree" &&
        (cd "$tree" && run_logged env GOTOOLCHAIN=local go build -trimpath -o "$tree/.dotfiles-check" ./cmd/dotfiles) &&
        run_logged "$tree/.dotfiles-check" check --repo "$tree" --machine "$MACHINE_FILE"; then
        status=0
    else
        log "ERROR: $ref's engine does not build with this machine's Go or cannot plan $MACHINE_FILE (see above); skipping merge and push"
        status=1
    fi
    rm -rf -- "$tree"
    return "$status"
}

github_repo() {
    local url
    url=$(git remote get-url --push origin) || return
    if [[ "$url" =~ ^(https://github\.com/|git@github\.com:|ssh://git@github\.com/)([a-zA-Z0-9_.-]+/[a-zA-Z0-9_.-]+)$ ]]; then
        printf '%s\n' "${BASH_REMATCH[2]%.git}"
    elif [[ "$url" == *github.com* ]]; then
        log "ERROR: Cannot determine GitHub repository for signature verification" >&2
        return 1
    fi
}

verify_github_commits() {
    local repo="$1" commits="$2" sha reason attempt
    [[ -n "$repo" ]] || return 0
    while IFS= read -r sha; do
        [[ -n "$sha" ]] || continue
        reason='verification unavailable'
        for attempt in 1 2 3; do
            reason=$(gh api "repos/$repo/commits/$sha" --jq '.commit.verification | if .verified then "verified" else .reason end') || reason='verification unavailable'
            [[ "$reason" == verified ]] && break
            [[ $attempt -eq 3 ]] || sleep 2
        done
        if [[ "$reason" != verified ]]; then
            log "ERROR: GitHub commit $sha is unverified: $reason"
            if [[ "$reason" == bad_email ]]; then
                log "ERROR: Git user.email must match a verified email on the signing key"
            fi
            return 1
        fi
    done <<< "$commits"
}

sync_git_repo() (
    local repo_dir="$1" auto_resolve="${2:-false}" branch changes untracked sha commits repo attempt
    cd "$repo_dir" || return
    git rev-parse --git-dir >/dev/null 2>&1 || { log "WARN: Not a Git repository: $repo_dir"; return 1; }
    repo_idle || return
    if repo_busy; then return 0; fi
    branch=$(git symbolic-ref --quiet --short HEAD) || { log "ERROR: Detached HEAD; skipping sync"; return 1; }
    signing_ready || return
    log "INFO: Syncing ${repo_dir##*/}"

    local has_remote=false
    if git remote get-url origin >/dev/null 2>&1; then
        has_remote=true
        if [[ "$(git rev-parse --abbrev-ref --symbolic-full-name '@{upstream}' 2>/dev/null)" != "origin/$branch" ]]; then
            log "ERROR: Set an origin tracking branch before automatic sync"
            return 1
        fi
        run_logged git fetch origin || return
    fi
    changes=$(git status --porcelain --untracked-files=no) || return
    untracked=$(git ls-files --others --exclude-standard | wc -l | tr -d ' ') || return
    if [[ "$untracked" -gt 0 ]]; then
        log "INFO: ${repo_dir##*/} has $untracked untracked file(s); sync never publishes new files, so commit them by hand"
    fi
    if [[ -n "$changes" ]]; then
        # Tracked files only: a file a tool drops into the tree is never published.
        git add -u -- . ':(exclude,glob)**/*.local' ':(exclude,glob)**/.env*' ':(exclude,glob)**/*.secret*' || return
        if ! git diff --cached --quiet; then
            scan_dotfiles --staged || return
            run_logged git commit -S -m "auto: sync $(date '+%Y-%m-%d %H:%M') from $(stable_host)" || return
            sha=$(git rev-parse HEAD) || return
            run_logged git verify-commit "$sha" || return
        fi
    fi
    [[ "$has_remote" == true ]] || return 0
    if [[ -n "$(git status --porcelain --untracked-files=no)" ]]; then
        log "ERROR: Excluded local changes remain; skipping merge and push"
        return 1
    fi
    repo=$(github_repo) || return
    if [[ -n "$repo" ]] && ! command -v gh >/dev/null; then
        log "ERROR: Install gh to verify GitHub commit signatures before publishing"
        return 1
    fi
    if [[ "$repo_dir" == "$DOTFILES_DIR" ]] && ! upstream_ready "origin/$branch"; then return 1; fi
    for attempt in 1 2 3; do
        integrate_remote "$branch" "$auto_resolve" || return
        commits=$(git rev-list "origin/$branch..HEAD") || return
        [[ -n "$commits" ]] || return 0
        while IFS= read -r sha; do run_logged git verify-commit "$sha" || return; done <<< "$commits"
        scan_dotfiles "--log-opts=origin/$branch..HEAD" || return
        if run_logged git push origin "HEAD:refs/heads/$branch"; then
            verify_github_commits "$repo" "$commits" || return
            log "INFO: Pushed verified commits for ${repo_dir##*/}"
            return 0
        fi
        [[ $attempt -eq 3 ]] && break
        sleep "$((attempt * 5))"
        run_logged git fetch origin || return
    done
    log "ERROR: Push failed after three attempts"
    return 1
)

sync_auxiliary_repos() {
    local dir result=0
    for dir in "$SYNC_DIR"/*/; do
        [[ -d "${dir}.git" || -f "${dir}.git" ]] || continue
        sync_git_repo "${dir%/}" true || result=1
    done
    return "$result"
}
sync_dotfiles() { sync_git_repo "$DOTFILES_DIR"; }

# sync_overlays: bring each overlay machine.toml lists (one private checkout per
# context this machine belongs to) up to date before apply reads it. The engine
# names them, so where overlays live is decided in one place.
sync_overlays() {
    local dirs dir result=0
    [[ -f "$MACHINE_FILE" ]] || return 0
    build_engine || return
    if ! dirs=$("$DOTFILES_BIN" overlays --machine "$MACHINE_FILE"); then
        log "ERROR: Cannot list the overlays in $MACHINE_FILE"
        return 1
    fi
    while IFS= read -r dir; do
        [[ -n "$dir" ]] || continue
        if [[ ! -d "$dir/.git" && ! -f "$dir/.git" ]]; then
            log "ERROR: $MACHINE_FILE lists overlay ${dir##*/}, which is not cloned at $dir; clone its repository there, or remove it from the list"
            result=1
            continue
        fi
        sync_git_repo "$dir" || result=1
    done <<< "$dirs"
    return "$result"
}

# build_engine: rebuild the binary when the checkout's engine sources are newer
# than it, which a pull that changes them makes them. GOTOOLCHAIN=local: a
# background job never downloads a Go toolchain.
build_engine() {
    local path stale="" sources=()
    for path in go.mod go.sum cmd internal; do
        [[ -e "$DOTFILES_DIR/$path" ]] && sources+=("$DOTFILES_DIR/$path")
    done
    if [[ -x "$DOTFILES_BIN" ]]; then
        [[ ${#sources[@]} -gt 0 ]] || return 0
        stale=$(find "${sources[@]}" -newer "$DOTFILES_BIN" -print -quit) || return
        [[ -n "$stale" ]] || return 0
    fi
    if ! command -v go >/dev/null; then
        log "ERROR: Go is not installed; cannot build $DOTFILES_BIN"
        return 1
    fi
    log "INFO: Building $DOTFILES_BIN"
    mkdir -p "${DOTFILES_BIN%/*}" || return
    if ! (cd "$DOTFILES_DIR" && run_logged env GOTOOLCHAIN=local go build -trimpath -o "$DOTFILES_BIN.tmp" ./cmd/dotfiles); then
        rm -f "$DOTFILES_BIN.tmp"
        log "ERROR: Building $DOTFILES_BIN failed"
        return 1
    fi
    mv -f "$DOTFILES_BIN.tmp" "$DOTFILES_BIN"
}

# apply_features: converge this machine on its features. The engine's own
# lock serializes it with a manual `dotfiles apply`.
apply_features() {
    if [[ ! -f "$MACHINE_FILE" ]]; then
        log "ERROR: No machine manifest at $MACHINE_FILE; run: $DOTFILES_BIN init --profiles <names>"
        return 1
    fi
    build_engine || return
    local status=0
    run_logged "$DOTFILES_BIN" apply --repo "$DOTFILES_DIR" || status=$?
    case $status in
        0) return 0 ;;
        1) log "WARN: dotfiles apply left problems to resolve; see above, or run: $DOTFILES_BIN doctor" ;;
        *) log "ERROR: dotfiles apply failed (exit $status)" ;;
    esac
    return 1
}

# sync_otel_agent: a pull can move the telemetry collector's pinned release
# together with a config only that release reads, and the config is a link into
# the checkout. Converging right after apply installs the release and restarts
# the collector on it, before anything else restarts it on the old binary.
# Machines that never enrolled are skipped by the script itself.
sync_otel_agent() {
    if ! run_logged "$DOTFILES_DIR/bin/otel-agent" converge; then
        log "ERROR: the telemetry collector did not converge; see above, or run: $DOTFILES_DIR/bin/otel-agent status"
        return 1
    fi
}

# Register through each client so it owns the locks and writes to its user config.
# OpenCode's global file belongs to the feature and is already linked by apply.
sync_github_mcp() (
    local launcher="$HOME/.local/bin/agent-mcp" helper="$HOME/.claude/mcp/github-headers.sh"
    local config="${CLAUDE_CONFIG_DIR:-$HOME}/.claude.json" url='https://api.githubcopilot.com/mcp/' state
    local PATH="$HOME/.local/bin:${HOMEBREW_PREFIX:-/opt/homebrew}/bin:/usr/local/bin:/home/linuxbrew/.linuxbrew/bin:$PATH"
    [[ -x "$launcher" ]] || return 0
    # Exclude any project-scoped server named github from the registration check.
    cd / || return 1
    if command -v claude >/dev/null; then
        state=missing
        if [[ -e "$config" ]]; then
            state=$(jq -er --arg url "$url" --arg helper "$helper" '
                .mcpServers.github | if . == null then "missing"
                elif .type == "http" and .url == $url and .headersHelper == $helper then "managed"
                else "custom" end' "$config") || return 1
        fi
        case "$state" in
            missing)
                jq -cn --arg url "$url" --arg helper "$helper" \
                    '{type:"http", url:$url, headers:{"X-MCP-Readonly":"true"}, headersHelper:$helper}' |
                    claude mcp add-json --scope user github - || return 1 ;;
            custom) log "WARN: keeping the existing Claude user MCP server named github" ;;
        esac
    fi
    if command -v codex >/dev/null; then
        state=$(codex mcp list --json | jq -er --arg launcher "$launcher" '
            map(select(.name == "github")) | first | if . == null then "missing"
            elif .transport.command == $launcher and .transport.args == ["github"] then "managed"
            else "custom" end') || return 1
        case "$state" in
            missing) codex mcp add github -- "$launcher" github || return 1 ;;
            custom) log "WARN: keeping the existing Codex user MCP server named github" ;;
        esac
    fi
)

# run_mode MODE: one sync run's work.
run_mode() {
    local status=0
    case "${1:-sync}" in
        check) log "INFO: Sync lock is available" ;;
        sync|all)
            check_connectivity || return 0
            # Apply right after the merges: a pull that moves tracked files
            # leaves links to their old paths until it runs, and apply reads
            # the overlays too. The telemetry collector converges on the files
            # apply linked. The Brewfile apply generates is installed next,
            # then mise's tools (mise is one of the packages), then Claude Code
            # where it is missing (jq, which reads the features, is a package).
            sync_dotfiles || status=1
            sync_overlays || status=1
            apply_features || status=1
            sync_otel_agent || status=1
            sync_brewfile || status=1
            sync_mise_tools || status=1
            sync_claude_code || status=1
            sync_github_mcp || status=1
            sync_auxiliary_repos || status=1
            if [[ $status -eq 0 ]]; then log "INFO: Sync complete"; else log "ERROR: Sync completed with failures"; fi
            ;;
        dotfiles) check_connectivity || return 0; sync_dotfiles || status=$? ;;
        overlays) check_connectivity || return 0; sync_overlays || status=$? ;;
        repos) check_connectivity || return 0; sync_auxiliary_repos || status=$? ;;
        build) build_engine || status=$? ;;
        apply) apply_features || status=$? ;;
        github-mcp) sync_github_mcp || status=$? ;;
        otel-agent) sync_otel_agent || status=$? ;;
        brewfile) sync_brewfile || status=$? ;;
        mise) sync_mise_tools || status=$? ;;
        claude-code) check_connectivity || return 0; sync_claude_code || status=$? ;;
        *) printf 'Usage: %s {sync|dotfiles|overlays|repos|build|apply|otel-agent|github-mcp|brewfile|mise|claude-code|all|check}\n' "$0"; return 1 ;;
    esac
    return "$status"
}

main() {
    mkdir -p "$LOG_DIR" "$SYNC_DIR"
    local status=0
    acquire_lock || status=$?
    [[ $status -ne 75 ]] || return 0
    [[ $status -eq 0 ]] || return "$status"
    rotate_log "$LOG_FILE"
    # This shell holds the lock until it returns; the work runs without it.
    without_sync_lock run_mode "$@" || status=$?
    return "$status"
}

if [[ "${BASH_SOURCE[0]}" == "$0" ]]; then main "$@"; fi
